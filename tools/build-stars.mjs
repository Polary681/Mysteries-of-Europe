// Builds src/world/stars-data.js (the real night sky used by the landing scene and the page sky) from the
// Yale Bright Star Catalogue, 5th revised edition (Hoffleit & Warren 1991, public data), in the JSON form published
// at https://github.com/brettonw/YaleBrightStarCatalog (MIT): file bsc5-short.json.
//   node tools/build-stars.mjs path/to/bsc5-short.json [maxMagnitude=5.3]
// Output: one flat array, 4 integers per star: RA (J2000, tenths of a degree), Dec (tenths of a degree),
// visual magnitude x100, colour temperature / 100 K. Stars are sorted brightest first.
import fs from "node:fs"; import path from "node:path"; import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = process.argv[2], maxMag = +(process.argv[3] || 5.3);
if (!src) { console.error("usage: node tools/build-stars.mjs bsc5-short.json [maxMag]"); process.exit(1); }
const cat = JSON.parse(fs.readFileSync(src, "utf8"));
const ra = s => { const m = /(\d+)h\s*(\d+)m\s*([\d.]+)s/.exec(s); return (+m[1] + +m[2] / 60 + +m[3] / 3600) * 15; };
const dec = s => { const m = /([+-])(\d+)°\s*(\d+)′\s*([\d.]+)″/.exec(s); const v = +m[2] + +m[3] / 60 + +m[4] / 3600; return m[1] === "-" ? -v : v; };
const stars = cat.filter(s => s.V && s.RA && s.Dec && +s.V <= maxMag).map(s => [ra(s.RA), dec(s.Dec), +s.V, +(s.K || 6000)]).sort((a, b) => a[2] - b[2]);
const flat = [];
for (const [r, d, v, k] of stars) flat.push(Math.round(r * 10), Math.round(d * 10), Math.round(v * 100), Math.round(Math.min(40000, Math.max(2000, k)) / 100));
const out = `/* GENERATED by tools/build-stars.mjs from the Yale Bright Star Catalogue (BSC5; JSON by B. Wade, MIT) - do not edit.
   ${stars.length} stars brighter than magnitude ${maxMag}, J2000. Per star: RA*10 (deg), Dec*10 (deg), V*100, temperature/100 (K). */
export const STAR_COUNT = ${stars.length};
export const STARS = [${flat.join(",")}];
`;
fs.writeFileSync(path.join(root, "src/world/stars-data.js"), out);
console.log(`wrote ${stars.length} stars (V <= ${maxMag}), ${(out.length / 1024).toFixed(1)} KB`);
